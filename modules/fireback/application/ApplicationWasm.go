//go:build wasm

package application

import (
	"embed"
	"maps"
	"strings"

	"github.com/gin-gonic/gin"
	"github.com/torabian/fireback/modules/fireback/gintools"
	"github.com/urfave/cli/v3"
	"gorm.io/gorm"
)

// Kept field-for-field identical to Application.go's (!wasm) Application and
// ModuleProvider - see that file's own doc comments for what each field is for.
// A module's wiring file (AbacModule.go, NotificationModule.go, ...) fills in
// the same struct literal regardless of build target, so the two definitions
// diverging (as they used to - this file only had roughly half the fields
// before) breaks compilation the moment a module sets a field only the other
// side declared. urfave/cli/v3 itself compiles fine under GOOS=js (verified),
// so there's no reason for the *cli.Command-typed fields to be wasm-unsafe -
// what's actually unsafe (readline via envm, real HTTP server lifecycle, ...)
// lives in files excluded by their own //go:build !wasm instead (Entrypoint.go,
// HttpServer.go, CliActions.go, clitools/*).
type Application struct {

	// application title, or name. it will be used only on cli or other descriptive places
	Title string

	// Indication that this project is microservice. Some functionalities might be limited
	MicroService bool

	// prefixes the entire api generated by fireback into a prefix, for example /api
	// it's useful to move all api in a prefix
	ApiPrefix string

	// modules created by fireback are injected here
	Modules []*ModuleProvider

	// Custom cli actions or command that you might want to add to the project
	CliActions func() []*cli.Command

	SetupWebServerHook func(*gin.Engine, *Application)
	SeedersSync        func()
	MockSync           func()
	PublicFolders      []gintools.PublicFolderInfo
}

type MigrationScript struct {
	Exec func() error
}

// Entities also can be bundled into one
type EntityBundle struct {
	Permissions           []PermissionInfo
	AutoMigrationEntities []interface{}
	CliCommands           []*cli.Command
	MockProvider          func()
	MigrationScripts      []MigrationScript
}

type ModuleProvider struct {
	EntityProvider      func(*gorm.DB) error
	MockHandler         func()
	SeederHandler       func()
	Namespace           string
	MigrationFunction   func(x *Application, db *gorm.DB)
	AppendCli           func(x *Application) []*cli.Command
	MockWriterHandler   func(languages []string)
	PermissionsProvider []PermissionInfo
	Name                string
	CliHandlers         []*cli.Command
	Definitions         *embed.FS
	Translations        map[string]map[string]string

	GoMigrateDirectory *embed.FS

	// On goose or go migrate, there is such table to keep knowledge of how much migration
	// already has happened. If empty, module name is used, but when it's duplicate name or
	// nested modules then it would be good to change it.
	DatabaseMigrationHistoryName string

	Children      []*ModuleProvider
	EntityBundles []EntityBundle

	// A set of functions that you can add, when project is being initialised then they will be called.
	// each module can have those hook inits, for example abac adds some other questions.
	OnEnvInit func(c *cli.Command) error

	// Called once during app startup (see commonHeadlessStarter), after the database
	// connection is available but before the CLI/web server actually run - the
	// equivalent of GinWebServerInitHooks for anything a module needs to kick off
	// itself rather than wire onto a router (e.g. eventbus.ModuleSetup uses this to
	// start its background goroutine only when a project actually registers the
	// eventbus module, instead of every project paying for it unconditionally).
	OnAppStart func(x *Application) error

	// When a gin web server is being created, the group for this module
	// will be looking for this function. Could be used to manually add routes or other configuration
	GinWebServerInitHooks []func(g *gin.RouterGroup, x *Application) error

	// Returns this module's own generated `config:` struct (e.g. a call to that
	// module's own emi-generated LoadConfiguration(), or just &config from its
	// package) as a bare interface{}. fireback.GetCombinedConfigInfo reflects over it
	// (same envconfig/description tags GoConfigGenerate already emits on every field)
	// to fold it into one combined config listing - the same way abac.Menu lets a
	// module contribute AppMenu items without interfacetools importing it back. A
	// func rather than a static value so it's re-read live (a module's config can be
	// mutated at runtime, e.g. via its own generated "config <field> set" CLI command).
	ConfigProvider func() interface{}
}

func (x *ModuleProvider) ProvideMockImportHandler(t func()) {
	x.MockHandler = t
}

// Override the namespace of the module, for exporting to front-end
// documentation, url
func (x *ModuleProvider) WithNamespace(namespace []string) *ModuleProvider {
	x.Namespace = strings.Join(namespace, "/")
	return x
}

func (x *ModuleProvider) ProvideSeederImportHandler(t func()) {
	x.SeederHandler = t
}

func (x *ModuleProvider) ProvideMockWriterHandler(t func(languages []string)) {
	x.MockWriterHandler = t
}

func (x *ModuleProvider) ProvideEntityHandlers(t func(*gorm.DB) error) {
	x.EntityProvider = t
}

func (x *ModuleProvider) ProvidePermissionHandler(items ...[]PermissionInfo) {
	for _, item := range items {
		x.PermissionsProvider = append(x.PermissionsProvider, item...)
	}
}

func (x *ModuleProvider) ProvideTranslationList(items ...map[string]map[string]string) {
	if x.Translations == nil {
		x.Translations = map[string]map[string]string{}
	}

	for _, item := range items {
		maps.Copy(x.Translations, item)
	}
}

// Adds CLI handlers to the module. You can call this as many times as you wish,
// They all will be added next to each other.
func (x *ModuleProvider) ProvideCliHandlers(t []*cli.Command) {
	x.CliHandlers = append(x.CliHandlers, t...)
}

// Registers a function returning this module's own generated `config:` struct, so
// it gets folded into the combined config listing - see ConfigProvider's own doc
// comment above.
func (x *ModuleProvider) ProvideConfigHandler(t func() interface{}) {
	x.ConfigProvider = t
}

type PermissionInfo struct {
	Name        string `yaml:"name,omitempty" json:"name,omitempty"`
	Description string `yaml:"description,omitempty" json:"description,omitempty"`
	CompleteKey string `yaml:"completeKey,omitempty" json:"completeKey,omitempty"`
	GoVariable  string `yaml:"-" json:"-"`
}
