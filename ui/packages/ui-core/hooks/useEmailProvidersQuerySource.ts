import {
  useEmailProviderBrowseActionQuery,
  EmailProviderBrowseActionQueryParams,
} from "@fireback/ui-core/sdk/messaging/EmailProviderBrowseAction";
import { type EmailProviderDto } from "@fireback/ui-core/sdk/messaging/EmailProviderDto";
import { type UseRemoteQuery } from "../types/remoteQuery";

// Adapts useEmailProviderBrowseActionQuery (the generated per-action hook, returning a raw
// @tanstack/react-query result whose payload is the {data: {items, ...}} envelope)
// into the {query, items, keyExtractor} shape FormSelect/FormSelectMultiple's
// querySource prop expects. Replaces the old useGetEmailProviders hook (deleted along with the
// rest of the legacy "Generated by fireback 1.3.2" sdk/modules tree), which returned
// that shape directly.
//
// Bug fix: this used to call useEmailProviderBrowseActionQuery({}) unconditionally,
// completely ignoring the params FormSelect actually passes (itemsPerPage,
// searchPhrase as the user types) - so the dropdown always showed the same
// unfiltered handful of rows regardless of what was typed. Now forwards both.
export const useEmailProvidersQuerySource = (params?: UseRemoteQuery) => {
  const query = useEmailProviderBrowseActionQuery({
    qs: new EmailProviderBrowseActionQueryParams({
      itemsPerPage: params?.query?.itemsPerPage ?? 200,
      searchPhrase: params?.query?.searchPhrase || undefined,
    }),
  });
  const items = ((query.data as any)?.data?.items ?? []) as EmailProviderDto[];
  return {
    query: query as any,
    items,
    keyExtractor: (item: EmailProviderDto) => item.uniqueId,
  };
};
