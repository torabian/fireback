import {
  useGsmProviderBrowseActionQuery,
  GsmProviderBrowseActionQueryParams,
} from "../../sdk/messaging/GsmProviderBrowseAction";
import { type GsmProviderDto } from "../../sdk/messaging/GsmProviderDto";
import { type UseRemoteQuery } from "../types/remoteQuery";

// Adapts useGsmProviderBrowseActionQuery (the generated per-action hook, returning a raw
// @tanstack/react-query result whose payload is the {data: {items, ...}} envelope)
// into the {query, items, keyExtractor} shape FormSelect/FormSelectMultiple's
// querySource prop expects. Replaces the old useGetGsmProviders hook (deleted along with the
// rest of the legacy "Generated by fireback 1.3.2" sdk/modules tree), which returned
// that shape directly.
//
// Bug fix: this used to call useGsmProviderBrowseActionQuery({}) unconditionally,
// completely ignoring the params FormSelect actually passes (itemsPerPage,
// searchPhrase as the user types) - so the dropdown always showed the same
// unfiltered handful of rows regardless of what was typed. Now forwards both.
export const useGsmProvidersQuerySource = (params?: UseRemoteQuery) => {
  const query = useGsmProviderBrowseActionQuery({
    qs: new GsmProviderBrowseActionQueryParams({
      itemsPerPage: params?.query?.itemsPerPage ?? 200,
      searchPhrase: params?.query?.searchPhrase || undefined,
    }),
  });
  const items = ((query.data as any)?.data?.items ?? []) as GsmProviderDto[];
  return {
    query: query as any,
    items,
    keyExtractor: (item: GsmProviderDto) => item.uniqueId,
  };
};
